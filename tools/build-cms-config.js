#!/usr/bin/env node
/* ===================================================================
   Generate the PAGE COPY section of admin/config.yml
   ===================================================================
       node tools/build-cms-config.js

   The data collections in admin/config.yml are hand-written, because
   their help text is the difference between a director who can use
   the CMS and one who phones you. The page-copy section is not: it is
   135 fields mechanically derived from data/pages/*.json, and writing
   those by hand would guarantee a typo.

   Everything between the cms:pages markers is replaced. Anything
   outside them is left alone.

   LABELS
     Keys look like "four-pillars__h3-2". A director should never see
     that, so each becomes "Four pillars — subheading 2" plus a hint
     quoting the current text, which is what she will actually
     recognise on the page.
=================================================================== */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const PAGES_DIR = path.join(ROOT, "data", "pages");
const CONFIG = path.join(ROOT, "admin", "config.yml");

/* Friendly names for the pages themselves. */
const PAGE_LABELS = {
  "index": "Home page",
  "about": "About page",
  "ty-story": "Ty's Story page",
  "programs": "Programs page (intro text)",
  "get-involved": "Get Involved page (intro text)",
  "donate": "Donate page (intro text)",
  "contact": "Contact page (intro text)",
  "impact": "Impact page (intro text)",
  "resources": "Resources page (intro text)",
  "whats-happening": "What's Happening page (intro text)",
  "where-your-money-goes": "Where Your Money Goes page",
  "404": "Page-not-found page",
  "thank-you": "Thank-you page"
};

const TAG_LABELS = {
  h1: "main heading",
  h2: "heading",
  h3: "subheading",
  p: "paragraph",
  blockquote: "quote"
};

function titleCase(s) {
  return s.replace(/-/g, " ").replace(/^\w/, function (c) { return c.toUpperCase(); });
}

/* YAML-safe double-quoted scalar. */
function q(s) {
  return '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
}

/* Strip tags and squeeze whitespace, for the "currently reads" hint. */
function plain(html) {
  return String(html).replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
}

function fieldFor(key, value) {
  const m = key.match(/^(.*)__([a-z0-9]+)-(\d+)$/);
  const section = m ? m[1] : key;
  const tag = m ? m[2] : "p";
  const n = m ? m[3] : "1";

  const tagLabel = TAG_LABELS[tag] || tag;
  const label = titleCase(section) + " — " + tagLabel +
                (Number(n) > 1 ? " " + n : "");

  const current = plain(value);
  const snippet = current.length > 90 ? current.slice(0, 90) + "…" : current;

  /* A long paragraph gets a text area; a heading gets a single line. */
  const widget = (tag === "p" || tag === "blockquote") && current.length > 80
    ? "text" : "string";

  return [
    "      - name: " + q(key),
    "        label: " + q(label),
    "        widget: " + widget,
    "        required: false",
    "        hint: " + q("Currently reads: “" + snippet + "”")
  ].join("\n");
}

function main() {
  if (!fs.existsSync(PAGES_DIR)) {
    console.error("data/pages does not exist. Run tools/extract-copy.js first.");
    process.exit(1);
  }

  const files = fs.readdirSync(PAGES_DIR)
    .filter(function (f) { return f.endsWith(".json"); })
    .sort();

  const lines = [
    "# cms:pages:start  GENERATED by tools/build-cms-config.js — do not hand-edit.",
    "  # =================================================================",
    "  # PAGE COPY",
    "  # Every heading and paragraph on the marketing pages.",
    "  # Privacy Policy and Terms are deliberately absent: they carry",
    "  # legal meaning and are changed by the developer, not here.",
    "  # =================================================================",
    "  - name: pages",
    "    label: Page wording",
    "    description: >-",
    "      The words on each page. Change one and it is live in about a",
    "      minute. If a box is blank the page keeps whatever it says now.",
    "    files:"
  ];

  let total = 0;

  files.forEach(function (file) {
    const name = file.replace(/\.json$/, "");
    const data = JSON.parse(fs.readFileSync(path.join(PAGES_DIR, file), "utf8"));
    const keys = Object.keys(data).filter(function (k) { return k !== "_comment"; });
    if (!keys.length) return;
    total += keys.length;

    lines.push(
      "      - name: " + q(name),
      "        label: " + q(PAGE_LABELS[name] || titleCase(name)),
      "        file: " + q("data/pages/" + file),
      "        format: json",
      "        fields:"
    );
    keys.forEach(function (k) {
      lines.push(fieldFor(k, data[k]).replace(/^ {6}/gm, "          "));
    });
  });

  lines.push("# cms:pages:end");

  const block = lines.join("\n");
  let cfg = fs.readFileSync(CONFIG, "utf8");
  const re = /# cms:pages:start[\s\S]*?# cms:pages:end/;
  if (!re.test(cfg)) {
    console.error("Markers not found in admin/config.yml");
    process.exit(1);
  }
  cfg = cfg.replace(re, block);
  fs.writeFileSync(CONFIG, cfg);

  console.log("admin/config.yml: " + total + " page-copy fields across " +
    files.length + " pages");
}

main();
